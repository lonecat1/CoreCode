"""终端美化层 —— 仿 Claude Code 的行模式界面。

    theme.py   配色与字形（`NO_COLOR` / `TERM=dumb` / 显式开关）
    width.py   显示宽度（CJK/Emoji 2 列、组合符 0 列）
    render.py  所有可视元素的渲染（纯字符串变换）

## 为什么不做全屏 TUI

Claude Code 的默认界面本身就是**美化过的行模式 REPL**，不是全屏 TUI。
这个选择决定了可靠性：全屏 TUI 依赖 raw mode、非阻塞读键、光标定位三样
与终端实现强耦合的能力，任何一环在用户的实际终端里不成立，界面就表现为
「画出来了但按键没反应」。行模式把这些依赖全部消除，只剩「往 stdout 写
文本」——在任何终端、任何重定向、任何 CI 里都成立。

本包**只做字符串变换，不碰 stdout**：所有函数接收数据、返回文本，由调用方
决定何时打印。因此可以被完整测试，也能在管道里安全使用。
"""

