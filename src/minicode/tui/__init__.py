"""终端 TUI —— 仿 Claude Code 的内联实时区域。

    theme.py     配色与字形（Claude Code 的视觉语言，遵守 NO_COLOR）
    width.py     显示宽度（CJK/Emoji 算 2 列、组合符算 0 列）
    screen.py    **内联实时区域**：原地重绘，不占备用屏幕
    app.py       状态 · 转录条目 · 布局组装 · 按键处理（全是纯函数）
    terminal.py  平台原生取键 + ANSI 能力探测（Windows 需启用 VT）
    runner.py    交互循环（回合跑在后台线程）

## 为什么用内联而不是全屏

全屏方案（备用屏幕 + `ESC[<行>;1H` 绝对定位）有一个致命脆弱点：它要求
「渲染出的行数」恰好等于「终端行数」。一旦不等——哪怕只多一行——写入就会
触发滚动，屏幕整体上移，之后所有绝对行号全部错位，画面必然错乱。

内联模式只在自占的几行里原地重绘，**不需要知道终端总行数**，因此从结构上
消除了这个问题。历史内容留在正常滚动缓冲里，用户仍可向上滚动查看。

## 分层的意义

有难度的算法（宽度、折行、行比对、布局组装、按键处理）全在纯函数里，
因此能被真正验证；无法在自动化环境里驱动的原始终端交互被压缩到
`terminal.py`，并且按键源可注入，于是连交互循环也能用脚本按键跑完。
"""

